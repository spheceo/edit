// Writes apps/server/src/embedded.gen.ts, the entry of the release binary
// (plan §4): it imports every file the binary carries `with { type: "file" }`
// (so `bun build --compile` puts them inside it), registers them, loads the
// addon from inside the binary, then runs main.ts. Sound effects and other
// assets a module imports itself `with { type: "file" }` come along anyway.
//
//     bun apps/server/scripts/embed.ts --native crates/edit-native/edit-native.node \
//         [--window target/release/edit-window] [--web apps/web/dist]
//     bun build apps/server/src/embedded.gen.ts --compile --outfile package/edit …

import * as fs from "node:fs";
import * as nodePath from "node:path";

const root = nodePath.join(import.meta.dir, "../../..");
const flag = (name: string) => {
  const at = process.argv.indexOf(name);
  return at >= 0 ? process.argv[at + 1] : undefined;
};
const absolute = (path: string) => nodePath.resolve(process.cwd(), path);

const web = absolute(flag("--web") ?? nodePath.join(root, "apps/web/dist"));
const addon = flag("--native");
const window = flag("--window");
const out = absolute(flag("--out") ?? nodePath.join(root, "apps/server/src/embedded.gen.ts"));
const dir = nodePath.dirname(out);

if (addon === undefined || !fs.existsSync(absolute(addon))) {
  console.error("embed: --native <path to edit-native.node> is required (build it with `just native`)");
  process.exit(2);
}
if (window !== undefined && !fs.existsSync(absolute(window))) {
  console.error(`embed: no window helper at ${window}`);
  process.exit(2);
}
if (!fs.existsSync(nodePath.join(web, "index.html"))) {
  console.error(`embed: ${web} has no index.html (run \`just web\`)`);
  process.exit(2);
}

/** Every file under `folder`, relative to it, sorted. */
function walk(folder: string, prefix = ""): string[] {
  const out: string[] = [];
  for (const entry of fs.readdirSync(nodePath.join(folder, prefix), { withFileTypes: true })) {
    const relative = prefix === "" ? entry.name : `${prefix}/${entry.name}`;
    if (entry.isDirectory()) out.push(...walk(folder, relative));
    else if (entry.isFile() && entry.name !== ".DS_Store") out.push(relative);
  }
  return out.sort();
}

/** An import specifier for `path` from the generated file. */
const specifier = (path: string) => {
  const relative = nodePath.relative(dir, path).split(nodePath.sep).join("/");
  return JSON.stringify(relative.startsWith(".") ? relative : `./${relative}`);
};

const files = walk(web);
const lines = [
  "// Generated by apps/server/scripts/embed.ts for a release build; don't edit or commit it.",
  "/* eslint-disable */",
  'import { useEmbedded } from "./embedded.ts";',
  'import { useNative, wrap, type Native } from "./native/index.ts";',
  ...files.map((file, index) => `import web${index} from ${specifier(nodePath.join(web, file))} with { type: "file" };`),
];
if (window !== undefined) lines.push(`import editWindow from ${specifier(absolute(window))} with { type: "file" };`);
lines.push(
  "",
  "// A static require: bun embeds the addon and loads it from inside the binary.",
  `useNative(wrap(require(${specifier(absolute(addon))}) as Native));`,
  "useEmbedded({",
  "  web: new Map<string, string>([",
  ...files.map((file, index) => `    [${JSON.stringify(file)}, web${index}],`),
  "  ]),",
  `  window: ${window !== undefined ? "editWindow" : "null"},`,
  "});",
  "",
  'await import("./main.ts");',
  "",
);
fs.writeFileSync(out, lines.join("\n"));
console.log(`embed: ${files.length} UI files, the addon${window !== undefined ? ", the window helper" : ""} → ${nodePath.relative(process.cwd(), out)}`);
